"""
4 - Crie um dicionário e verifique se uma chave específica existe dentro desse dicionário. 
"""

dicionario = {"nome": "Alice", "idade": 30, "cidade": "São Paulo"}

if "idade" in dicionario:
    print("A chave 'idade' existe no dicionário.")
else: 
    print("A chave 'idade' não existe no dicionário.")

if "casa" in dicionario:
    print("A chave 'casa' existe no dicionário.")
else: 
    print("A chave 'casa' não existe no dicionário.")